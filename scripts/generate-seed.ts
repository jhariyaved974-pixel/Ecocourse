// Generates supabase/seed.sql (development sample catalogue) from
// scripts/render/catalog.ts so data and rendered assets always match.
//   npx tsx scripts/generate-seed.ts
import { writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { CATEGORIES, COLLECTIONS, PRODUCTS, PRODUCT_VIEWS } from './render/catalog';

const ROOT = path.resolve(__dirname, '..');
const q = (v: string | null | undefined) => (v === null || v === undefined ? 'null' : `'${v.replace(/'/g, "''")}'`);
const slugify = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '');
const sizeSort = (label: string) => Number(label.replace(/[^0-9.]/g, '')) || 0;

const lines: string[] = [];
lines.push('-- Development seed: original AUREN sample catalogue (placeholder products).');
lines.push('-- Generated by scripts/generate-seed.ts. Safe to re-run: skips products that already exist.');
lines.push("select set_config('app.inventory_write', 'on', true);");
lines.push('');

// Categories & collections exist in the baseline migration; ensure they are present for older databases.
for (const [i, c] of CATEGORIES.entries()) {
  lines.push(`insert into public.categories (name, slug, description, sort_order) values (${q(c.name)}, ${q(c.slug)}, ${q(c.description)}, ${i + 1}) on conflict (slug) do nothing;`);
}
for (const [i, c] of COLLECTIONS.entries()) {
  lines.push(`insert into public.collections (name, slug, description, sort_order) values (${q(c.name)}, ${q(c.slug)}, ${q(c.description)}, ${i + 1}) on conflict (slug) do nothing;`);
}
lines.push('');

const missing: string[] = [];
PRODUCTS.forEach((p, productIndex) => {
  const pv = `p_${p.slug.replace(/-/g, '_')}`;
  lines.push(`-- ${p.name}`);
  lines.push('do $$');
  lines.push(`declare ${pv} uuid; v_color uuid; v_variant uuid; v_asset uuid; v_model uuid;`);
  lines.push('begin');
  lines.push(`  if exists (select 1 from public.products where slug = ${q(p.slug)}) then return; end if;`);
  const modelUrl = `/models/${p.slug}.glb`;
  if (!existsSync(path.join(ROOT, 'public', modelUrl))) missing.push(modelUrl);
  lines.push(`  insert into public.media_assets (kind, external_url, label, alt_text, mime_type) values ('model', ${q(modelUrl)}, ${q(`${p.name} — 3D model`)}, ${q(`Interactive 3D model of ${p.name}`)}, 'model/gltf-binary') returning id into v_model;`);
  lines.push(`  insert into public.products (name, slug, sku, category_id, gender, short_description, description, price, sale_price, status, published_at, is_featured, is_new_arrival, is_bestseller, is_trending, tags, model_asset_id, size_guide_id, seo_title, seo_description)`);
  lines.push(`  values (${q(p.name)}, ${q(p.slug)}, ${q(p.sku)}, (select id from public.categories where slug = ${q(p.category)}), ${q(p.gender)}, ${q(p.short)}, ${q(p.description)}, ${p.price * 100}, ${p.salePrice ? p.salePrice * 100 : 'null'}, 'draft', now() - interval '${PRODUCTS.length - productIndex} days', ${!!p.flags.featured}, ${!!p.flags.new}, ${!!p.flags.bestseller}, ${!!p.flags.trending}, array[${p.tags.map(q).join(', ')}]::text[], v_model, (select id from public.size_guides where is_default limit 1), ${q(`${p.name} — ${p.colorways[0].name}`.slice(0, 70))}, ${q(p.short.slice(0, 170))})`);
  lines.push(`  returning id into ${pv};`);
  p.attributes.forEach(([label, value], i) => {
    lines.push(`  insert into public.product_attributes (product_id, label, value, sort_order) values (${pv}, ${q(label)}, ${q(value)}, ${i + 1});`);
  });
  let mediaOrder = 0;
  p.colorways.forEach((c, ci) => {
    lines.push(`  insert into public.product_colors (product_id, name, hex, family, sort_order) values (${pv}, ${q(c.name)}, ${q(c.hex)}, ${q(c.family)}, ${ci + 1}) returning id into v_color;`);
    p.sizes.forEach((size, si) => {
      const stock = p.stock[ci]?.[si] ?? 0;
      const sku = `${p.sku}-${slugify(c.name).toUpperCase().slice(0, 6)}-${size.replace(/[^0-9]/g, '')}`;
      lines.push(`  insert into public.product_variants (product_id, color_id, size_label, size_sort, sku, stock_on_hand) values (${pv}, v_color, ${q(size)}, ${sizeSort(size)}, ${q(sku)}, ${stock}) returning id into v_variant;`);
      if (stock > 0) {
        lines.push(`  insert into public.inventory_movements (variant_id, quantity_delta, reason, on_hand_after, note) values (v_variant, ${stock}, 'initial', ${stock}, 'Seed stock');`);
      }
    });
    for (const view of PRODUCT_VIEWS) {
      const url = `/images/products/${p.slug}/${slugify(c.name)}-${view}.webp`;
      if (!existsSync(path.join(ROOT, 'public', url))) missing.push(url);
      const alt = `${p.name} in ${c.name}, ${view === 'side' ? 'side profile' : view === 'top' ? 'top view' : 'three-quarter view'}`;
      mediaOrder += 1;
      lines.push(`  insert into public.media_assets (kind, external_url, label, alt_text, mime_type, width, height) values ('image', ${q(url)}, ${q(`${p.name} — ${c.name} (${view})`)}, ${q(alt)}, 'image/webp', 1200, 1200) returning id into v_asset;`);
      lines.push(`  insert into public.product_media (product_id, asset_id, color_id, sort_order, is_cover) values (${pv}, v_asset, v_color, ${mediaOrder}, ${ci === 0 && view === 'hero34'});`);
    }
  });
  for (const col of p.collections) {
    lines.push(`  insert into public.collection_products (collection_id, product_id) select id, ${pv} from public.collections where slug = ${q(col)} on conflict do nothing;`);
  }
  lines.push(`  update public.products set status = 'published' where id = ${pv};`);
  lines.push('end $$;');
  lines.push('');
});

writeFileSync(path.join(ROOT, 'supabase/seed.sql'), lines.join('\n'));
console.log(`Wrote supabase/seed.sql (${PRODUCTS.length} products).`);
if (missing.length) console.warn(`Warning: ${missing.length} referenced asset(s) are missing, e.g. ${missing[0]}. Run: node scripts/render/run.mjs`);
