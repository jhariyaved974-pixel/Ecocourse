// Generates supabase/seed.sql (Save The Money development sample catalogue)
// from scripts/render/catalog.ts so data and rendered assets always match.
//   npx tsx scripts/generate-seed.ts
import { writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { CATEGORIES, COLLECTIONS, PRODUCTS, PRODUCT_VIEWS, type SampleProduct } from './render/catalog';

const ROOT = path.resolve(__dirname, '..');
const q = (v: string | null | undefined) => (v === null || v === undefined ? 'null' : `'${v.replace(/'/g, "''")}'`);
const slugify = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '');
const VIEW_ALT: Record<string, string> = { hero34: 'three-quarter view', side: 'side view', top: 'top view', back34: 'back three-quarter view' };
const VARIANT_SKU = /^[A-Z0-9][A-Z0-9-]{1,59}$/;

/** A product whose only option value is 'Standard' has no options (single variant per colour). */
const hasOptions = (p: SampleProduct) => !(p.sizes.length === 1 && p.sizes[0] === 'Standard');

/** SKU suffix for an option value: the digits of "UK n" sizes, otherwise its uppercase alphanumerics ('S/M' -> 'SM'). */
function optionCode(value: string): string {
  if (/^UK\s*\d+(\.\d+)?$/i.test(value.trim())) return value.replace(/[^0-9]/g, '');
  return value.toUpperCase().replace(/[^A-Z0-9]/g, '');
}

function variantSku(p: SampleProduct, colourName: string, option: string): string {
  // First six characters of the colour slug, without a dangling hyphen ('Storm Grey' -> 'STORM').
  const colour = slugify(colourName).toUpperCase().slice(0, 6).replace(/-+$/, '');
  const sku = `${p.sku}-${colour}${hasOptions(p) ? `-${optionCode(option)}` : ''}`;
  if (!VARIANT_SKU.test(sku)) throw new Error(`Variant SKU "${sku}" (${p.slug}) does not match ${VARIANT_SKU}`);
  return sku;
}

// Sanity checks so a catalogue mistake fails here, not halfway through a database reset.
const slugs = new Set(CATEGORIES.map((c) => c.slug));
const seenSkus = new Set<string>();
for (const p of PRODUCTS) {
  if (!slugs.has(p.category)) throw new Error(`${p.slug}: unknown category "${p.category}"`);
  if (p.stock.length !== p.colorways.length || p.stock.some((row) => row.length !== p.sizes.length)) {
    throw new Error(`${p.slug}: stock must be [colourway][option] (${p.colorways.length} × ${p.sizes.length})`);
  }
  for (const c of p.colorways) {
    for (const size of p.sizes) {
      const sku = variantSku(p, c.name, size);
      if (seenSkus.has(sku)) throw new Error(`Duplicate variant SKU ${sku}`);
      seenSkus.add(sku);
    }
  }
}

const lines: string[] = [];
lines.push('-- Development seed: Save The Money sample catalogue (original placeholder products).');
lines.push('-- Generated by scripts/generate-seed.ts. Safe to re-run: skips products that already exist.');
lines.push("select set_config('app.inventory_write', 'on', true);");
lines.push('');

// Categories & collections exist in the baseline migration; ensure they are present for older databases.
// Departments come first in CATEGORIES, so a sub-category's parent always exists when it is inserted.
const levelOrder = new Map<string, number>();
for (const c of CATEGORIES) {
  const level = c.parent ? 'sub' : 'top';
  const ord = (levelOrder.get(level) ?? 0) + 1;
  levelOrder.set(level, ord);
  const parent = c.parent ? `(select id from public.categories where slug = ${q(c.parent)})` : 'null';
  lines.push(`insert into public.categories (parent_id, name, slug, description, sort_order) values (${parent}, ${q(c.name)}, ${q(c.slug)}, ${q(c.description)}, ${ord}) on conflict (slug) do nothing;`);
}
for (const [i, c] of COLLECTIONS.entries()) {
  lines.push(`insert into public.collections (name, slug, description, sort_order) values (${q(c.name)}, ${q(c.slug)}, ${q(c.description)}, ${i + 1}) on conflict (slug) do nothing;`);
}
lines.push('');

const missing: string[] = [];
PRODUCTS.forEach((p, productIndex) => {
  const pv = `p_${p.slug.replace(/-/g, '_')}`;
  lines.push(`-- ${p.name}`);
  lines.push('do $$');
  lines.push(`declare ${pv} uuid; v_color uuid; v_variant uuid; v_asset uuid; v_model uuid;`);
  lines.push('begin');
  lines.push(`  if exists (select 1 from public.products where slug = ${q(p.slug)}) then return; end if;`);
  const modelUrl = `/models/${p.slug}.glb`;
  if (!existsSync(path.join(ROOT, 'public', modelUrl))) missing.push(modelUrl);
  lines.push(`  insert into public.media_assets (kind, external_url, label, alt_text, mime_type) values ('model', ${q(modelUrl)}, ${q(`${p.name} — 3D model`)}, ${q(`Interactive 3D model of ${p.name}`)}, 'model/gltf-binary') returning id into v_model;`);
  // size_guide_id stays null: the product's category (or its department) supplies the guide.
  lines.push(`  insert into public.products (name, slug, sku, category_id, gender, short_description, description, price, sale_price, status, published_at, is_featured, is_new_arrival, is_bestseller, is_trending, tags, variant_label, model_asset_id, size_guide_id, seo_title, seo_description)`);
  lines.push(`  values (${q(p.name)}, ${q(p.slug)}, ${q(p.sku)}, (select id from public.categories where slug = ${q(p.category)}), ${q(p.gender)}, ${q(p.short)}, ${q(p.description)}, ${p.price * 100}, ${p.salePrice ? p.salePrice * 100 : 'null'}, 'draft', now() - interval '${PRODUCTS.length - productIndex} days', ${!!p.flags.featured}, ${!!p.flags.new}, ${!!p.flags.bestseller}, ${!!p.flags.trending}, array[${p.tags.map(q).join(', ')}]::text[], ${q(p.variantLabel)}, v_model, null, ${q(`${p.name} — ${p.colorways[0].name}`.slice(0, 70))}, ${q(p.short.slice(0, 170))})`);
  lines.push(`  returning id into ${pv};`);
  p.attributes.forEach(([label, value], i) => {
    lines.push(`  insert into public.product_attributes (product_id, label, value, sort_order) values (${pv}, ${q(label)}, ${q(value)}, ${i + 1});`);
  });
  let mediaOrder = 0;
  p.colorways.forEach((c, ci) => {
    lines.push(`  insert into public.product_colors (product_id, name, hex, family, sort_order) values (${pv}, ${q(c.name)}, ${q(c.hex)}, ${q(c.family)}, ${ci + 1}) returning id into v_color;`);
    p.sizes.forEach((size, si) => {
      const stock = p.stock[ci]?.[si] ?? 0;
      // Option sort = position in the product's option list (1-based).
      lines.push(`  insert into public.product_variants (product_id, color_id, size_label, size_sort, sku, stock_on_hand) values (${pv}, v_color, ${q(size)}, ${si + 1}, ${q(variantSku(p, c.name, size))}, ${stock}) returning id into v_variant;`);
      if (stock > 0) {
        lines.push(`  insert into public.inventory_movements (variant_id, quantity_delta, reason, on_hand_after, note) values (v_variant, ${stock}, 'initial', ${stock}, 'Seed stock');`);
      }
    });
    for (const view of PRODUCT_VIEWS) {
      const url = `/images/products/${p.slug}/${slugify(c.name)}-${view}.webp`;
      if (!existsSync(path.join(ROOT, 'public', url))) missing.push(url);
      const alt = `${p.name} in ${c.name}, ${VIEW_ALT[view] ?? view}`;
      mediaOrder += 1;
      lines.push(`  insert into public.media_assets (kind, external_url, label, alt_text, mime_type, width, height) values ('image', ${q(url)}, ${q(`${p.name} — ${c.name} (${view})`)}, ${q(alt)}, 'image/webp', 1200, 1200) returning id into v_asset;`);
      lines.push(`  insert into public.product_media (product_id, asset_id, color_id, sort_order, is_cover) values (${pv}, v_asset, v_color, ${mediaOrder}, ${ci === 0 && view === 'hero34'});`);
    }
  });
  for (const col of p.collections) {
    lines.push(`  insert into public.collection_products (collection_id, product_id) select id, ${pv} from public.collections where slug = ${q(col)} on conflict do nothing;`);
  }
  lines.push(`  update public.products set status = 'published' where id = ${pv};`);
  lines.push('end $$;');
  lines.push('');
});

writeFileSync(path.join(ROOT, 'supabase/seed.sql'), lines.join('\n'));
console.log(`Wrote supabase/seed.sql (${PRODUCTS.length} products, ${seenSkus.size} variants).`);
if (missing.length) console.warn(`Warning: ${missing.length} referenced asset(s) are missing, e.g. ${missing[0]}. Run: node scripts/render/run.mjs`);
