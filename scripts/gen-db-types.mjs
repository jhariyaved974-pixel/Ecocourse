#!/usr/bin/env node
// Generates src/lib/database.types.ts in the same shape as `supabase gen types`
// by introspecting a Postgres database (default: the local stack).
//   DATABASE_URL=postgres://... node scripts/gen-db-types.mjs
// With the Supabase CLI you can instead run:
//   supabase gen types typescript --project-id <ref> > src/lib/database.types.ts
import pg from 'pg';
import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const client = new pg.Client({ connectionString: process.env.DATABASE_URL ?? 'postgres://postgres@127.0.0.1:54322/postgres' });
await client.connect();

const SKIP_TABLES = new Set(['_local_migrations']);
const enums = (await client.query(`
  select t.typname::text as name, array_agg(e.enumlabel::text order by e.enumsortorder) as labels
  from pg_type t join pg_enum e on e.enumtypid = t.oid join pg_namespace n on n.oid = t.typnamespace
  where n.nspname = 'public' group by t.typname order by t.typname`)).rows;
const enumNames = new Set(enums.map((e) => e.name));

function tsType(udt, isArray) {
  const base = udt.replace(/^_/, '');
  let t;
  if (enumNames.has(base)) t = `Database["public"]["Enums"]["${base}"]`;
  else if (['uuid', 'text', 'varchar', 'bpchar', 'citext', 'name', 'inet', 'date', 'time', 'timestamp', 'timestamptz', 'interval'].includes(base)) t = 'string';
  else if (['int2', 'int4', 'int8', 'float4', 'float8', 'numeric'].includes(base)) t = 'number';
  else if (base === 'bool') t = 'boolean';
  else if (['json', 'jsonb'].includes(base)) t = 'Json';
  else t = 'unknown';
  return isArray ? `${t}[]` : t;
}

const tables = (await client.query(`
  select c.relname::text as name, c.relkind::text as relkind
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind in ('r', 'v', 'p') order by c.relname`)).rows.filter((t) => !SKIP_TABLES.has(t.name));

const columns = (await client.query(`
  select c.table_name, c.column_name, c.udt_name, c.data_type, c.is_nullable = 'YES' as nullable,
         c.column_default is not null as has_default, c.is_identity = 'YES' as identity,
         c.is_generated = 'ALWAYS' as generated, c.identity_generation, c.ordinal_position
  from information_schema.columns c where c.table_schema = 'public' order by c.table_name, c.ordinal_position`)).rows;

const fks = (await client.query(`
  select con.conname::text as conname, src.relname::text as source, tgt.relname::text as target,
    array(select a.attname::text from unnest(con.conkey) with ordinality k(attnum, ord) join pg_attribute a on a.attrelid = con.conrelid and a.attnum = k.attnum order by k.ord) as cols,
    array(select a.attname::text from unnest(con.confkey) with ordinality k(attnum, ord) join pg_attribute a on a.attrelid = con.confrelid and a.attnum = k.attnum order by k.ord) as refcols,
    exists (
      select 1 from pg_index i where i.indrelid = con.conrelid and i.indisunique and i.indpred is null
        and (select array_agg(x order by x) from unnest(i.indkey::int2[]) x) = (select array_agg(x order by x) from unnest(con.conkey) x)
    ) as one_to_one
  from pg_constraint con
  join pg_class src on src.oid = con.conrelid join pg_namespace sn on sn.oid = src.relnamespace
  join pg_class tgt on tgt.oid = con.confrelid join pg_namespace tn on tn.oid = tgt.relnamespace
  where con.contype = 'f' and sn.nspname = 'public' and tn.nspname = 'public'
  order by src.relname, con.conname`)).rows;

const functions = (await client.query(`
  select p.proname::text as name, p.prorettype::regtype::text as rettype, p.proretset as retset,
    coalesce(p.proargnames, '{}') as argnames, coalesce(p.proallargtypes::regtype[]::text[], p.proargtypes::regtype[]::text[]) as argtypes,
    coalesce(p.proargmodes::text[], '{}') as argmodes, p.pronargdefaults as ndefaults, p.pronargs as nargs,
    (select array_agg(t.typname::text order by u.ord) from unnest(coalesce(p.proallargtypes, p.proargtypes::oid[])) with ordinality u(oid, ord) join pg_type t on t.oid = u.oid) as argudts,
    (select t.typname::text from pg_type t where t.oid = p.prorettype) as retudt
  from pg_proc p join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public' and p.prokind = 'f'
    and p.prorettype <> 'trigger'::regtype
    and has_function_privilege('authenticated', p.oid, 'execute') or (n.nspname = 'public' and p.prokind = 'f' and has_function_privilege('service_role', p.oid, 'execute') and p.prorettype <> 'trigger'::regtype)
  order by p.proname`)).rows;

const out = [];
out.push('// Generated by scripts/gen-db-types.mjs. Do not edit by hand.');
out.push('export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[]\n');
out.push('export type Database = {\n  public: {\n    Tables: {');
for (const t of tables.filter((t) => t.relkind !== 'v')) {
  const cols = columns.filter((c) => c.table_name === t.name);
  const row = cols.map((c) => `          ${c.column_name}: ${tsType(c.udt_name, c.data_type === 'ARRAY')}${c.nullable ? ' | null' : ''}`);
  const ins = cols.map((c) => {
    if (c.generated || c.identity_generation === 'ALWAYS') return `          ${c.column_name}?: never`;
    const opt = c.nullable || c.has_default || c.identity;
    return `          ${c.column_name}${opt ? '?' : ''}: ${tsType(c.udt_name, c.data_type === 'ARRAY')}${c.nullable ? ' | null' : ''}`;
  });
  const upd = cols.map((c) => {
    if (c.generated || c.identity_generation === 'ALWAYS') return `          ${c.column_name}?: never`;
    return `          ${c.column_name}?: ${tsType(c.udt_name, c.data_type === 'ARRAY')}${c.nullable ? ' | null' : ''}`;
  });
  const rels = fks.filter((f) => f.source === t.name).map((f) =>
    `          {\n            foreignKeyName: "${f.conname}"\n            columns: [${f.cols.map((c) => `"${c}"`).join(', ')}]\n            isOneToOne: ${f.one_to_one}\n            referencedRelation: "${f.target}"\n            referencedColumns: [${f.refcols.map((c) => `"${c}"`).join(', ')}]\n          },`);
  out.push(`      ${t.name}: {\n        Row: {\n${row.join('\n')}\n        }\n        Insert: {\n${ins.join('\n')}\n        }\n        Update: {\n${upd.join('\n')}\n        }\n        Relationships: [\n${rels.join('\n')}\n        ]\n      }`);
}
out.push('    }\n    Views: {\n      [_ in never]: never\n    }\n    Functions: {');
const seen = new Set();
for (const f of functions) {
  if (seen.has(f.name)) continue;
  seen.add(f.name);
  const modes = f.argmodes.length ? f.argmodes : f.argtypes.map(() => 'i');
  const inArgs = [];
  const tableCols = [];
  f.argtypes.forEach((type, i) => {
    const name = f.argnames[i] || `arg${i}`;
    const udt = f.argudts?.[i] ?? 'unknown';
    const isArray = type.endsWith('[]');
    if (modes[i] === 'i' || modes[i] === 'b') inArgs.push({ name, ts: tsType(udt, isArray) });
    if (modes[i] === 't' || modes[i] === 'o') tableCols.push({ name, ts: tsType(udt, isArray) });
  });
  const firstDefault = f.nargs - f.ndefaults;
  const args = inArgs.map((a, i) => `          ${a.name}${i >= firstDefault ? '?' : ''}: ${a.ts}`);
  let returns;
  if (tableCols.length) returns = `{\n${tableCols.map((c) => `            ${c.name}: ${c.ts}`).join('\n')}\n          }[]`;
  else if (f.rettype === 'void') returns = 'undefined';
  else returns = tsType(f.retudt, f.rettype.endsWith('[]')) + (f.retset ? '[]' : '');
  out.push(`      ${f.name}: {\n        Args: ${args.length ? `{\n${args.join('\n')}\n        }` : 'Record<PropertyKey, never>'}\n        Returns: ${returns}\n      }`);
}
out.push('    }\n    Enums: {');
for (const e of enums) out.push(`      ${e.name}: ${e.labels.map((l) => `"${l}"`).join(' | ')}`);
out.push('    }\n    CompositeTypes: {\n      [_ in never]: never\n    }\n  }\n}\n');
out.push(`type PublicSchema = Database["public"]
export type Tables<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Row"]
export type TablesInsert<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Insert"]
export type TablesUpdate<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Update"]
export type Enums<T extends keyof PublicSchema["Enums"]> = PublicSchema["Enums"][T]
`);
await writeFile(path.join(ROOT, 'src/lib/database.types.ts'), out.join('\n'));
await client.end();
console.log(`Wrote src/lib/database.types.ts (${tables.length} tables, ${seen.size} functions, ${enums.length} enums)`);
